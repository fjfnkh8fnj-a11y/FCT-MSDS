export function basicAssessment(title, description){
 const topic=topics.find(t=>t.terms.test(title))||topics.find(t=>t.terms.test(description));
 const from=(bank,items)=>items.map(([prompt,choices,answer,explanation])=>({
  prompt,choices,answer,explanation:explanation+' 참고: '+bank.source
 }));
 return {
  label:(topic||general).label,
  fallback:!topic,
  questions:topic?[...from(topic,topic.items),...from(general,general.items.slice(0,2))]:from(general,general.items)
 };
}

